const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const { pgcrypto } = require('@electric-sql/pglite/contrib/pgcrypto');
const Checkout = require('../js/checkout');
const db = new PGlite({ extensions: { pgcrypto } });
const buyer = '11111111-1111-4111-8111-111111111111';
const creator = '22222222-2222-4222-8222-222222222222';
const actAs = id => db.query('select set_config(\'gm.test.uid\', $1, false)', [id]);
const rpc = async (fn, data) => (await db.query('select public.'+ fn +'($1::jsonb) result', [JSON.stringify(data)])).rows[0].result;
const checkout = data => rpc('gm_checkout', data);
(async () => {
  await db.exec(`
    create schema auth;
    create role anon;
    create role authenticated;
    create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb, encrypted_password text);
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('gm.test.uid', true), '')::uuid $$;
  `);
  assert.equal((await db.query('show server_version')).rows[0].server_version.split('.')[0] >= 16, true);
  const schema = fs.readFileSync('server/supabase.sql','utf8');
  await db.exec(schema);
  await db.exec(schema);
  console.log('PASS  SQL aplicado duas vezes em PostgreSQL local (PGlite); Auth simulado.');
  const catalog = (await db.query('select * from catalogo_demo')).rows;
  assert.equal(catalog.length,10);
  for(const item of catalog){
    const base = Checkout.demoRecipe(item.id);
    assert.deepEqual([item.titulo,item.chef_id,Number(item.preco),Number(item.valor_kit)], [base.name,base.chefId,base.price,base.kitPrice]);
  }
  console.log('PASS  10 receitas e preços de demonstração iguais ao catálogo JavaScript.');
  await db.query("insert into auth.users values ($1,'cliente@exemplo.test','{\"name\":\"Pessoa Teste\"}',extensions.crypt('senha-teste',extensions.gen_salt('bf',4)))", [buyer]);
  await db.query("insert into auth.users values ($1,'chef@exemplo.test','{\"kind\":\"criador\",\"name\":\"Chef Teste\",\"doc\":\"demo.pdf\",\"termo\":true}',extensions.crypt('senha-teste',extensions.gen_salt('bf',4)))", [creator]);
  await db.query("update criador_conteudo set status_validacao='APROVADO' where id_usuario=$1",[creator]);
  await actAs(creator);
  const {recipe} = await rpc('gm_recipe_create',{name:'Receita SQL',price:25.9,kitPrice:45,minutes:18,ingredientes:'Arroz',instrucoes:'Cozinhe'});
  await actAs(buyer);
  const custom = {type:'receita',refId:recipe.id,metodo:'pix'};
  const sale = await checkout({...custom,amount:0.01,cupom:'gastro10'});
  assert.equal(sale.tx.valor,23.31);
  assert.equal((await checkout({type:'receita',refId:'risoto-funghi',metodo:'pix',amount:1})).tx.valor,34.9);
  assert.equal((await checkout({type:'assinatura',refId:'torino',metodo:'pix',amount:1})).tx.valor,29);
  const kit = (await checkout({type:'kit',refId:recipe.id,metodo:'pix',termo:true,entrega:'retirada',amount:1,recipeName:'Outro nome'})).order;
  assert.equal(kit.recipeName,'Receita SQL');
  assert.equal(kit.valor,45);
  console.log('PASS  Receita publicada, kit, cupom e assinatura usam preço e título da base.');
  await assert.rejects(checkout({...custom,chefId:'torino'}),{code:'GM422'});
  await assert.rejects(checkout({...custom,refId:'r99999999'}),{code:'GM404'});
  await assert.rejects(checkout({type:'kit',refId:recipe.id,termo:true,entrega:'entrega',cep:'invalid',metodo:'pix'}),{code:'GM422'});
  const refused = await checkout({type:'receita',refId:'mousse-chocolate',metodo:'cartao',card_ok:false});
  assert.equal(refused.refused,true);
  const profile = (await db.query('select gm_me() as result')).rows[0].result;
  assert.ok(!profile.access.includes('mousse-chocolate'));
  assert.ok(profile.tx.some(t=>t.status==='RECUSADA' && t.http===402));
  await db.query("update criador_conteudo set status_validacao='REJEITADO' where id_usuario=$1",[creator]);
  await assert.rejects(checkout(custom),{code:'GM404'});
  const recipes = (await db.query('select gm_recipes() result')).rows[0].result.recipes;
  assert.equal(recipes.length,0);
  console.log('PASS  CEP inválido, referência inexistente, curadoria, recusa registrada e acesso preservado.');
  const grant = (await db.query("select has_function_privilege('anon','gm_delete_account(text,text)','execute') anon, to_regprocedure('gm_delete_account(text)') old")).rows[0];
  assert.deepEqual(grant,{anon:false,old:null});
  await assert.rejects(db.query("select gm_delete_account('EXCLUIR','outra')"),{code:'GM401'});
  await assert.rejects(db.query("select gm_delete_account('excluir','senha-teste')"),{code:'GM422'});
  await db.query("select gm_delete_account('EXCLUIR','senha-teste')");
  assert.equal((await db.query('select count(*) n from auth.users')).rows[0].n,1);
  assert.equal((await db.query('select count(*) n from transacao_financeira')).rows[0].n,0);
  console.log('PASS  Exclusão exige confirmação e senha conferida no banco; dados do comprador removidos em cascata.');
  await db.close();
})().catch(e=>{ console.error(e.message, e.code, e.detail); process.exitCode=1; });
